/**
 * 提取中文文本的拼音首字母
 * 例: "华润三九" → "HRSJ"
 * 非中文字符保留原样
 */
export function toPinyinInitials(text: string): string {
  if (!text) return '';
  let result = '';
  for (const char of text) {
    if (char >= '一' && char <= '鿿') {
      result += PINYIN_MAP[char] || '';
    } else if (/[A-Za-z0-9]/.test(char)) {
      result += char.toUpperCase();
    }
  }
  return result;
}
